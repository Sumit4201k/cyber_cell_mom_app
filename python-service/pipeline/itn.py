# Consolidated master map sorted by token length descending
ALL_WORD_NUMBERS = {}

# 1. Add English compound tens + units (e.g. "twenty five" -> "25", "twenty-five" -> "25")
for t_word, t_val in ENGLISH_TENS.items():
    for u_word, u_val in ENGLISH_UNITS.items():
        combined_val = str(t_val + u_val)
        ALL_WORD_NUMBERS[f"{t_word} {u_word}"] = combined_val
        ALL_WORD_NUMBERS[f"{t_word}-{u_word}"] = combined_val

# 2. Merge all language & dialect dictionaries
for d in (GUJARATI_WORDS_MAP, HINDI_WORDS_MAP, ENGLISH_WORDS_MAP, HINGLISH_WORDS_MAP):
    ALL_WORD_NUMBERS.update(d)

# 3. Sort words by length descending to ensure longer multi-word phrases match before substrings
SORTED_WORD_ENTRIES = sorted(ALL_WORD_NUMBERS.items(), key=lambda x: len(x[0]), reverse=True)


def _process_single_line(line: str) -> str:
    header = ""
    body = line
    m = re.match(r"^(\[\d+\.\d+s\s*->\s*\d+\.\d+s\]\s*)(.*)$", line)
    if m:
        header = m.group(1)
        body = m.group(2)

    # 1. Convert native Indic numeral glyphs (૦-૯ / ०-९) directly to ASCII digits (0-9)
    for glyph, ascii_digit in INDIC_NUMERAL_GLYPHS.items():
        body = body.replace(glyph, ascii_digit)

    # 2. Expand Repetition Multipliers
    for pattern, repl in REPETITION_PATTERNS:
        for _ in range(3):
            body = re.sub(pattern, repl, body, flags=re.IGNORECASE)

    # 3. Convert Spoken Words / Numbers to Digits
    for word, digit_str in SORTED_WORD_ENTRIES:
        pattern = rf"(?<![^\s,.\-_/]){re.escape(word)}(?![^\s,.\-_/])"
        body = re.sub(pattern, digit_str, body, flags=re.IGNORECASE)

    # 4. Secondary expansion for any newly created repetition digit pairs
    for pattern, repl in REPETITION_PATTERNS:
        for _ in range(2):
            body = re.sub(pattern, repl, body, flags=re.IGNORECASE)

    # 5. Merge digit sequences separated by spaces, commas, or periods into continuous numbers
    for _ in range(6):
        body = re.sub(r"(\d)[\s,\-\.]+(\d)", r"\1\2", body)

    return header + body


def apply_itn(text: str, target_lang: Optional[str] = None) -> str:
    """
    Exhaustive Multi-Lingual Inverse Text Normalization (ITN) Engine.
    Handles:
      1. Indic numeral Unicode glyphs (Gujarati/Devanagari ૦-૯ / ०-९ -> 0-9)
      2. Repetition multipliers across languages (double, triple, quadruple, do baar, tran vaar, etc.)
      3. Spoken phonetic, dialectal, and regional numbers to ASCII digits (English, Gujarati, Hindi, Hinglish)
      4. Continuous digit sequence normalization for phone numbers, bank accounts, Aadhaar, FIRs.
      5. Preserves timestamp headers [start -> end] with decimal precision.
    """
    if not text:
        return ""

    lines = text.split("\n")
    processed = [_process_single_line(l) for l in lines]
    return "\n".join(processed)

